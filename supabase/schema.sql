-- Status Rodeo schema export, generated 2026-10-06 from the live database, plus the
-- statuses content length constraint, verified against production on 2026-10-08, plus
-- the Hat Tips objects (hat_tips table, hat_tip_info function), applied in production and
-- verified with hat-tips-verify.sql (27 of 27 checks) on 2026-10-10, plus the avatar icons
-- (profiles.avatar, its check, the update policy and column grant), applied in production and
-- verified with avatar-icons-verify.sql (20 of 20 checks) on 2026-10-11.
-- plus the Edit and delete objects (statuses.edited_at, its trigger, the update and delete
-- policies and grants), applied in production on 2026-10-12 and checked with
-- status-edit-delete-verify.sql (23 of 24 as reported; the 24th was a wrong constraint name
-- in the check, now fixed).
-- Covers tables, foreign keys, check constraints, RLS, and policies.
-- Table grants are not included: anon and authenticated hold the Supabase default
-- grants on profiles and statuses, except UPDATE on profiles (see the avatar section below).
-- hat_tips is different: see its section below.
-- Requires the auth schema (present in every Supabase project) for auth.users.

create table public.profiles (
  user_id uuid not null primary key,
  created_at timestamp with time zone not null default now(),
  username text not null unique,
  display_name text not null,
  avatar text not null default 'cowboy-hat'::text
);

create table public.statuses (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  content text not null,
  visibility text not null default 'public'::text,
  created_at timestamp with time zone not null default now(),
  edited_at timestamp with time zone   -- set by a trigger, see Edit and delete
);

alter table public.profiles
  add constraint profiles_user_id_fkey
  foreign key (user_id) references auth.users(id);

alter table public.statuses
  add constraint statuses_user_id_fkey
  foreign key (user_id) references auth.users(id);

alter table public.statuses
  add constraint statuses_user_id_fkey1
  foreign key (user_id) references public.profiles(user_id);

-- Statuses are 1 to 280 characters (Unicode code points, the same count the browser
-- uses) and cannot be blank. Checked against the production constraint on
-- 2026-10-08. Postgres stores it as
-- CHECK (char_length(content) >= 1 AND char_length(content) <= 280 AND content !~ '^\s*$').
-- In production the constraint is named statuses_content_length_check (confirmed by Muse on
-- 2026-10-12; this file used to say statuses_content_check).
alter table public.statuses
  add constraint statuses_content_length_check
  check (
    char_length(content) between 1 and 280
    and content !~ '^\s*$'
  );

-- The avatar is the file name of one of the icons in public/avatars/icons/, without the
-- extension. It ends up in a URL path, so only a plain kebab-case name is allowed. The icons
-- are not listed here, so a new icon needs no SQL (the app shows the default for a name it
-- does not know). Same as supabase/avatar-icons.sql.
alter table public.profiles
  add constraint profiles_avatar_check
  check (avatar ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(avatar) <= 40);

alter table public.profiles enable row level security;
alter table public.statuses enable row level security;

create policy "Public profiles are viewable"
  on public.profiles for select to public
  using (true);

-- A signed-in user can update only their own profile row, and only the avatar column: UPDATE
-- is taken from anon and authenticated and granted back on that one column, which keeps
-- username, display_name, user_id and created_at read-only from the Data API.
revoke update on public.profiles from anon, authenticated;
grant update (avatar) on public.profiles to authenticated;

create policy "Users can update their own profile"
  on public.profiles for update to authenticated
  using (((select auth.uid() as uid) = user_id))
  with check (((select auth.uid() as uid) = user_id));

create policy "Public statuses are viewable"
  on public.statuses for select to public
  using (visibility = 'public'::text);

create policy "Users can create their own statuses"
  on public.statuses for insert to authenticated
  with check (((select auth.uid() as uid) = user_id));

-- Edit and delete (same as supabase/status-edit-delete.sql, applied 2026-10-12). A signed-in user can
-- update only their own statuses and only the content column, and delete only their own.
-- edited_at is set by the trigger when content really changes, never by the browser.
create or replace function public.statuses_set_edited_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.content is distinct from old.content then
    new.edited_at := now();
  else
    new.edited_at := old.edited_at;
  end if;

  return new;
end;
$$;

drop trigger if exists statuses_set_edited_at on public.statuses;
create trigger statuses_set_edited_at
  before update on public.statuses
  for each row execute function public.statuses_set_edited_at();

revoke update, delete on public.statuses from anon, authenticated;
grant delete on public.statuses to authenticated;
grant update (content) on public.statuses to authenticated;

create policy "Users can update their own statuses"
  on public.statuses for update to authenticated
  using (((select auth.uid() as uid) = user_id))
  with check (((select auth.uid() as uid) = user_id));

create policy "Users can delete their own statuses"
  on public.statuses for delete to authenticated
  using (((select auth.uid() as uid) = user_id));

-- ---------------------------------------------------------------------------
-- Hat Tips. Same objects as supabase/hat-tips.sql (the migration that was applied),
-- including its table grants, which here are deliberately NOT the Supabase default:
-- anon has no access, authenticated has select, insert and delete only.
-- ---------------------------------------------------------------------------

create table if not exists public.hat_tips (
  status_id bigint not null references public.statuses (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamp with time zone not null default now(),
  primary key (status_id, user_id)
);

-- The primary key serves lookups by status. This one serves the ON DELETE CASCADE
-- from auth.users and "my tips" lookups.
create index if not exists hat_tips_user_id_idx on public.hat_tips (user_id);

alter table public.hat_tips enable row level security;

-- Supabase grants every privilege on new tables to anon and authenticated. Take them
-- all back and give signed-in users only what the app needs (rows are immutable, so
-- there is no UPDATE).
revoke all on public.hat_tips from anon, authenticated;
grant select, insert, delete on public.hat_tips to authenticated;

drop policy if exists "Users see their own hat tips" on public.hat_tips;
create policy "Users see their own hat tips"
  on public.hat_tips for select to authenticated
  using ((select auth.uid()) = user_id);

-- Tipping is allowed only as yourself and only on a public status. The EXISTS check
-- runs under the statuses policy "Public statuses are viewable", so that policy hides
-- non-public statuses too; the explicit visibility test is a second layer, kept so
-- this policy does not depend on the other one staying as it is.
drop policy if exists "Users tip their hat as themselves" on public.hat_tips;
create policy "Users tip their hat as themselves"
  on public.hat_tips for insert to authenticated
  with check (
    (select auth.uid()) = user_id
    and exists (
      select 1
      from public.statuses s
      where s.id = status_id
        and s.visibility = 'public'
    )
  );

drop policy if exists "Users take back their own hat tips" on public.hat_tips;
create policy "Users take back their own hat tips"
  on public.hat_tips for delete to authenticated
  using ((select auth.uid()) = user_id);

-- Counts and the caller's own state for a batch of statuses, in one request.
-- SECURITY DEFINER so it can count rows the caller cannot read; it is kept narrow:
--   * only public statuses are returned (anything else is silently left out),
--   * only counts and the caller's own flag come back, never user ids,
--   * at most 100 ids are looked at per call,
--   * the search path is empty, so every name is schema-qualified.
-- Signed-out callers get tipped = false (auth.uid() is null).
create or replace function public.hat_tip_info(status_ids bigint[])
returns table (status_id bigint, tips bigint, tipped boolean)
language sql
stable
security definer
set search_path = ''
as $$
  select
    s.id,
    count(h.user_id),
    coalesce(bool_or(h.user_id = (select auth.uid())), false)
  from public.statuses s
  left join public.hat_tips h on h.status_id = s.id
  where s.id = any (status_ids[1:100])
    and s.visibility = 'public'
  group by s.id;
$$;

-- New functions are executable by PUBLIC (and, on Supabase, by default grants).
-- Reset that, then allow exactly the two API roles.
revoke all on function public.hat_tip_info(bigint[]) from public, anon, authenticated;
grant execute on function public.hat_tip_info(bigint[]) to anon, authenticated;
